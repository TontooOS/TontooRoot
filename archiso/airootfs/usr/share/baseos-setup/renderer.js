function formValue(name, fallback = '') {
  const data = new FormData(form);
  const value = data.get(name);
  return value === null || value === '' ? fallback : String(value);
}

function currentLanguage() {
  return formValue('language', 'en');
}

function text(key) {
  const language = currentLanguage();
  return copy[language][key] || copy.en[key] || key;
}

function translate() {
  const language = currentLanguage();
  document.documentElement.lang = language;
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.getAttribute('data-i18n');
    node.textContent = copy[language][key] || copy.en[key] || node.textContent;
  });
}

function setTheme(theme) {
  body.dataset.theme = theme === 'dark' ? 'dark' : 'light';
}

function selectedThemeColor() {
  return formValue('themeColor', '#2563eb');
}

function updateThemeColor() {
  document.documentElement.style.setProperty('--theme-accent', selectedThemeColor());
}

function hideStartupSplash() {
  if (!startupSplash) {
    return;
  }
  window.setTimeout(() => {
    startupSplash.classList.add('is-hidden');
  }, 1500);
}

function showSetupWizard() {
  bootChooser.classList.add('is-hidden');
  setupShell.classList.remove('hidden');
  setupShell.classList.add('is-visible');
  setupPanel.classList.remove('is-transitioning');
  void setupPanel.offsetWidth;
  setupPanel.dataset.transition = 'forward';
  setupPanel.classList.add('is-transitioning');
  goToStep(currentStep);
  playNextStepSound();
}

async function startLiveDesktop() {
  if (bootStatus) {
    bootStatus.textContent = text('startingLive');
  }

  tryLiveButton.disabled = true;
  installChoiceButton.disabled = true;

  if (!window.setupAPI || typeof window.setupAPI.tryLiveDesktop !== 'function') {
    if (bootStatus) {
      bootStatus.textContent = text('tryUnavailable');
    }
    tryLiveButton.disabled = false;
    installChoiceButton.disabled = false;
    return;
  }

  try {
    await window.setupAPI.tryLiveDesktop();
  } catch (error) {
    if (bootStatus) {
      bootStatus.textContent = error && error.message ? error.message : text('tryUnavailable');
    }
    tryLiveButton.disabled = false;
    installChoiceButton.disabled = false;
  }
}

function selectedNetworkLabel() {
  const mode = formValue('networkMode', 'lan');
  if (mode === 'lan') {
    return 'LAN';
  }
  return formValue('wifiSsid', 'Home-WiFi');
}

function selectedHarddriveLabel() {
  const selectedId = formValue('selectedHarddrive');
  const selected = harddrives.find((device) => device.id === selectedId);
  if (!selected) {
    return text('unset');
  }
  return `${selected.name} / ${selected.size}`;
}

function selectedAvatarInput() {
  return form.querySelector('[name="avatar"]:checked');
}

function selectedAvatarColor() {
  return formValue('avatarColor', '#2563eb');
}

function updateAvatarPreview() {
  const avatar = selectedAvatarInput();
  if (!avatar) {
    return;
  }
  avatarPreview.textContent = avatar.dataset.icon || '\uf007';
  document.documentElement.style.setProperty('--avatar-color', selectedAvatarColor());
}

function playNextStepSound() {
  try {
    nextStepSound.currentTime = 0;
    nextStepSound.play().catch(() => {});
  } catch (_error) {
    // Missing audio devices or codecs should never block setup navigation.
  }
}

function passwordMatches() {
  const password = formValue('password');
  const repeat = formValue('passwordRepeat');
  return password === repeat;
}

function inputByName(name) {
  return form.querySelector(`[name="${name}"]`);
}

function setInputInvalid(name, invalid) {
  const input = inputByName(name);
  if (!input) {
    return;
  }

  if (invalid) {
    input.setAttribute('aria-invalid', 'true');
  } else {
    input.removeAttribute('aria-invalid');
  }
}

function showWarning(node, messageKey, show) {
  if (!node) {
    return;
  }

  if (messageKey) {
    node.textContent = text(messageKey);
  }

  node.classList.toggle('hidden', !show);
}

function clearUserValidation() {
  ['username', 'firstName', 'lastName', 'computerName', 'password', 'passwordRepeat'].forEach((name) => {
    setInputInvalid(name, false);
  });
}

function validateUserStep(show = true) {
  clearUserValidation();

  const requiredFields = ['username', 'firstName', 'lastName', 'computerName', 'password', 'passwordRepeat'];
  const missingFields = requiredFields.filter((name) => !formValue(name).trim());

  if (missingFields.length) {
    missingFields.forEach((name) => setInputInvalid(name, true));
    showWarning(userWarning, 'userRequired', show);
    return false;
  }

  const username = formValue('username');
  if (!/^[a-z_][a-z0-9_-]{0,31}$/.test(username)) {
    setInputInvalid('username', true);
    showWarning(userWarning, 'usernameInvalid', show);
    return false;
  }

  const computerName = formValue('computerName');
  if (!/^[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?$/.test(computerName)) {
    setInputInvalid('computerName', true);
    showWarning(userWarning, 'computerNameInvalid', show);
    return false;
  }

  if (!passwordMatches()) {
    setInputInvalid('password', true);
    setInputInvalid('passwordRepeat', true);
    showWarning(userWarning, 'passwordMismatch', show);
    return false;
  }

  showWarning(userWarning, '', false);
  return true;
}

function validateSshStep(show = true) {
  const port = Number(formValue('sshPort', '22'));
  const valid = Number.isInteger(port) && port >= 1 && port <= 65535;
  setInputInvalid('sshPort', !valid);
  showWarning(sshWarning, 'sshPortInvalid', show && !valid);
  return valid;
}

function validateHarddriveStep(show = true) {
  const valid = Boolean(formValue('selectedHarddrive'));
  showWarning(harddriveValidation, 'installNoHarddrive', show && !valid);
  return valid;
}

function validateCurrentStep(show = true) {
  if (currentStep === 4) {
    return validateUserStep(show);
  }

  if (currentStep === 6) {
    return validateSshStep(show);
  }

  if (currentStep === lastInputStep) {
    return validateHarddriveStep(show);
  }

  return true;
}

function refreshVisibleValidation() {
  const showingWarning = [userWarning, sshWarning, harddriveValidation].some((node) => node && !node.classList.contains('hidden'));
  validateCurrentStep(showingWarning);
}

function collectPreview() {
  const firstName = formValue('firstName');
  const lastName = formValue('lastName');
  const username = formValue('username');
  const displayName = [firstName, lastName].filter(Boolean).join(' ') || username || text('unset');
  const sshEnabled = form.querySelector('[name="sshEnabled"]').checked;
  const sshRootLogin = form.querySelector('[name="sshRootLogin"]').checked;
  const sshPort = formValue('sshPort', '22');

  return [
    [text('summaryLanguage'), formValue('language', 'en') === 'de' ? 'Deutsch' : 'English'],
    [text('summaryKeyboard'), formValue('keyboard', 'us').toUpperCase()],
    [text('summaryTimezone'), formValue('timezone', 'Europe/Berlin')],
    [text('summaryNetwork'), selectedNetworkLabel()],
    [text('summaryUser'), displayName],
    [text('summaryComputer'), formValue('computerName', text('unset'))],
    [text('summaryTheme'), formValue('theme', 'light') === 'dark' ? text('darkMode') : text('lightMode')],
    [text('summarySsh'), `${sshEnabled ? text('enabled') : text('disabled')} / ${sshPort} / root: ${sshRootLogin ? text('yes') : text('no')}`],
    [text('summaryHarddrive'), selectedHarddriveLabel()]
  ];
}

function renderSummary() {
  summaryGrid.innerHTML = '';
  collectPreview().forEach(([label, value]) => {
    const item = document.createElement('div');
    item.className = 'summary-item';

    const labelNode = document.createElement('small');
    labelNode.textContent = label;

    const valueNode = document.createElement('strong');
    valueNode.textContent = value;

    item.append(labelNode, valueNode);
    summaryGrid.append(item);
  });
}

